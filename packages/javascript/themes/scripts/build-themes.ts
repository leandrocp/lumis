/**
 * Generates one TypeScript module per theme JSON file,
 * and copies normalized JSON files to dist/json/.
 *
 * Accepts a --step flag:
 *   --step=ts    Generate TypeScript modules only (run before tsup)
 *   --step=json  Copy normalized JSON to dist/json/ (run after tsup clean)
 *   (no flag)    Run both steps
 */

import fs from "node:fs";
import path from "node:path";
import { readThemes } from "./read-themes.js";

const pack = process.argv.includes("--pack=copyleft") ? "copyleft" : "default";
const PACKAGE_ROOT = path.resolve(
  import.meta.dirname,
  pack === "default" ? ".." : "../../themes-copyleft",
);
const THEMES_OUT = path.join(PACKAGE_ROOT, "themes");
const JSON_OUT = path.join(PACKAGE_ROOT, "dist/json");

function generateTS(themes: ReturnType<typeof readThemes>) {
  fs.rmSync(THEMES_OUT, { recursive: true, force: true });
  fs.mkdirSync(THEMES_OUT, { recursive: true });

  for (const { name, data } of themes) {
    const module = `// Do not edit. Auto-generated by scripts/build-themes.ts
import type { ThemeData } from '${pack === "default" ? "../src/types.js" : "@lumis-sh/themes"}'

const theme: ThemeData = ${JSON.stringify(data)}

export default theme
`;
    fs.writeFileSync(path.join(THEMES_OUT, `${name}.ts`), module);
  }

  console.log(`  ${themes.length} theme modules generated`);
}

function copyJSON(themes: ReturnType<typeof readThemes>) {
  fs.rmSync(JSON_OUT, { recursive: true, force: true });
  fs.mkdirSync(JSON_OUT, { recursive: true });
  const cssOut = path.join(PACKAGE_ROOT, "dist/css");
  fs.rmSync(cssOut, { recursive: true, force: true });
  fs.mkdirSync(cssOut, { recursive: true });

  for (const { name, file, data } of themes) {
    fs.writeFileSync(path.join(JSON_OUT, file), JSON.stringify(data));
    fs.copyFileSync(
      path.resolve(import.meta.dirname, `../../../../css/${name}.css`),
      path.join(cssOut, `${name}.css`),
    );
  }
  fs.rmSync(path.join(PACKAGE_ROOT, "dist/licenses"), { recursive: true, force: true });
  fs.cpSync(path.join(PACKAGE_ROOT, "pack"), path.join(PACKAGE_ROOT, "dist"), { recursive: true });
  if (pack === "default") {
    for (const { name } of readThemes("copyleft")) {
      const target = `@lumis-sh/themes-copyleft/${name}`;
      const out = path.join(PACKAGE_ROOT, `dist/themes/${name}`);
      fs.writeFileSync(`${out}.js`, `export { default } from ${JSON.stringify(target)};\n`);
      fs.writeFileSync(`${out}.cjs`, `module.exports = require(${JSON.stringify(target)});\n`);
      fs.writeFileSync(
        `${out}.d.ts`,
        'import type { ThemeData } from "../index.js";\ndeclare const theme: ThemeData;\nexport default theme;\n',
      );
      fs.copyFileSync(`${out}.d.ts`, `${out}.d.cts`);
    }
  }

  console.log(`  ${themes.length} JSON files copied to dist/json/`);
}

const step = process.argv.find((a) => a.startsWith("--step="))?.split("=")[1];
const themes = readThemes(pack);

if (!step || step === "ts") generateTS(themes);
if (!step || step === "json") copyJSON(themes);

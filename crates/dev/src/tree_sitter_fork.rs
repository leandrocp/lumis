//! Builds `crates/lumis-tree-sitter` from a pinned `tree-sitter` release plus
//! the patches beside it. Nothing in that crate is edited by hand: this is the
//! only writer, and `--check` fails when the committed crate is not its output.

use anyhow::{bail, ensure, Context, Result};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const CRATE_DIR: &str = "crates/lumis-tree-sitter";
const SYMBOL_PREFIX: &str = "lumis_";
const PREFIX_HEADER: &str = "lumis_prefix.h";
const INITIAL_VERSION: &str = "0.1.0";

/// What `crates/lumis-tree-sitter` authors by hand. Everything else in the
/// directory is generated and replaced on every sync.
const AUTHORED: &[&str] = &["upstream.toml", "patches", "CHANGELOG.md"];

#[derive(serde::Deserialize)]
struct Upstream {
    version: String,
    sha256: String,
}

struct Patch {
    file_name: String,
    subject: String,
    description: String,
}

pub(crate) fn sync(check: bool) -> Result<()> {
    let crate_dir = Path::new(CRATE_DIR);
    let upstream: Upstream = toml::from_str(
        &fs::read_to_string(crate_dir.join("upstream.toml"))
            .context("failed to read crates/lumis-tree-sitter/upstream.toml")?,
    )?;
    let staging = std::env::temp_dir().join(format!("lumis-tree-sitter-{}", std::process::id()));
    let _ = fs::remove_dir_all(&staging);
    let result = generate(crate_dir, &upstream, &staging).and_then(|()| {
        if check {
            compare(crate_dir, &staging)
        } else {
            replace(crate_dir, &staging)
        }
    });
    let _ = fs::remove_dir_all(&staging);
    result
}

fn generate(crate_dir: &Path, upstream: &Upstream, out: &Path) -> Result<()> {
    let archive = fetch_crate(&upstream.version)?;
    let actual = super::sha256_hex(&archive);
    ensure!(
        actual == upstream.sha256,
        "tree-sitter {} has SHA-256 {actual}, expected {}",
        upstream.version,
        upstream.sha256
    );
    let unpacked = out.with_extension("unpacked");
    let _ = fs::remove_dir_all(&unpacked);
    tar::Archive::new(flate2::read::GzDecoder::new(archive.as_slice()))
        .unpack(&unpacked)
        .context("failed to unpack the tree-sitter crate")?;
    fs::rename(
        unpacked.join(format!("tree-sitter-{}", upstream.version)),
        out,
    )?;
    let _ = fs::remove_dir_all(&unpacked);
    for leftover in ["Cargo.toml.orig", "Cargo.lock", ".cargo_vcs_info.json"] {
        let _ = fs::remove_file(out.join(leftover));
    }

    let patches = read_patches(&crate_dir.join("patches"))?;
    for patch in &patches {
        apply_patch(out, &crate_dir.join("patches").join(&patch.file_name))?;
    }
    let fingerprint = source_fingerprint(&out.join("src"))?;
    let symbols = exported_symbols(&out.join("src"))?;
    prefix_c_symbols(&out.join("src"), &symbols, &fingerprint)?;
    prefix_rust_imports(&out.join("binding_rust"), &symbols)?;
    verify_prefixed(&out.join("src"))?;
    let version = committed_version(crate_dir)?;
    rewrite_manifest(&out.join("Cargo.toml"), &version)?;
    fs::write(
        out.join("rustfmt.toml"),
        "# Generated by `mise run tree-sitter-sync`. Upstream's formatting, untouched.\ndisable_all_formatting = true\n",
    )?;
    fs::write(
        out.join("README.md"),
        readme(upstream, &patches, symbols.len()),
    )?;
    Ok(())
}

fn fetch_crate(version: &str) -> Result<Vec<u8>> {
    let cache = Path::new("target/lumis-tree-sitter");
    let path = cache.join(format!("tree-sitter-{version}.crate"));
    if let Ok(bytes) = fs::read(&path) {
        return Ok(bytes);
    }
    let url = format!("https://static.crates.io/crates/tree-sitter/tree-sitter-{version}.crate");
    println!("* downloading {url}");
    let bytes = super::download_bytes(&ureq::Agent::new_with_defaults(), &url)?;
    fs::create_dir_all(cache)?;
    fs::write(&path, &bytes)?;
    Ok(bytes)
}

/// Patches in application order. Each is a `git format-patch` file, whose
/// subject and message are the description the README publishes.
fn read_patches(dir: &Path) -> Result<Vec<Patch>> {
    let mut names: Vec<String> = fs::read_dir(dir)
        .with_context(|| format!("failed to read {}", dir.display()))?
        .map(|entry| Ok(entry?.file_name().to_string_lossy().into_owned()))
        .collect::<Result<_>>()?;
    names.retain(|name| {
        Path::new(name)
            .extension()
            .is_some_and(|ext| ext == "patch")
    });
    names.sort();
    names
        .into_iter()
        .map(|file_name| {
            let text = fs::read_to_string(dir.join(&file_name))?;
            let (subject, description) = patch_message(&text)
                .with_context(|| format!("{file_name} has no `Subject:` and description"))?;
            Ok(Patch {
                file_name,
                subject,
                description,
            })
        })
        .collect()
}

/// The subject and body of a `git format-patch` mail. Header continuation
/// lines are folded into the subject, and the `[PATCH n/m]` tag is dropped.
fn patch_message(text: &str) -> Option<(String, String)> {
    let (headers, rest) = text.split_once("\n\n")?;
    let mut subject = String::new();
    let mut in_subject = false;
    for line in headers.lines() {
        if let Some(value) = line.strip_prefix("Subject: ") {
            subject = value.to_string();
            in_subject = true;
        } else if in_subject && line.starts_with([' ', '\t']) {
            subject.push(' ');
            subject.push_str(line.trim());
        } else {
            in_subject = false;
        }
    }
    if let Some(stripped) = subject.strip_prefix("[PATCH") {
        subject = stripped.split_once("] ")?.1.to_string();
    }
    let body = rest.split_once("\n---\n")?.0;
    let description = body
        .lines()
        .filter(|line| !line.starts_with("(cherry picked from") && !line.contains("-by: "))
        .collect::<Vec<_>>()
        .join("\n")
        .trim()
        .to_string();
    (!subject.is_empty() && !description.is_empty()).then_some((subject, description))
}

fn apply_patch(root: &Path, patch: &Path) -> Result<()> {
    let output = Command::new("git")
        .args(["apply", "--whitespace=nowarn", "-p1"])
        .arg(patch.canonicalize()?)
        .current_dir(root)
        .output()
        .context("failed to run git apply")?;
    ensure!(
        output.status.success(),
        "{} does not apply to the pinned tree-sitter:\n{}",
        patch.display(),
        String::from_utf8_lossy(&output.stderr)
    );
    Ok(())
}

/// Every function and variable the C library defines with external linkage.
/// Read from the syntax tree, so a definition behind `#ifdef` counts whichever
/// branch a build takes, and a `static` one never does.
fn exported_symbols(src: &Path) -> Result<BTreeSet<String>> {
    let mut parser = tree_sitter::Parser::new();
    parser.set_language(&tree_sitter_c::LANGUAGE.into())?;
    let mut symbols = BTreeSet::new();
    let mut seen = BTreeSet::new();
    let mut pending = vec![src.join("lib.c").canonicalize()?];
    // The directories `build.rs` passes as `-I`, searched after the including file's own.
    let search = [src.to_path_buf(), src.with_file_name("include")];
    let mut files = Vec::new();
    let mut annotations = BTreeSet::new();
    while let Some(path) = pending.pop() {
        if !seen.insert(path.clone()) {
            continue;
        }
        let text = fs::read_to_string(&path)?;
        let tree = parser
            .parse(&text, None)
            .with_context(|| format!("failed to parse {}", path.display()))?;
        let mut includes = Vec::new();
        collect_definitions(
            tree.root_node(),
            text.as_bytes(),
            &mut BTreeSet::new(),
            &mut includes,
        );
        collect_annotation_macros(tree.root_node(), text.as_bytes(), &mut annotations);
        let dir = path.parent().unwrap_or(src).to_path_buf();
        for include in includes {
            let found = std::iter::once(&dir)
                .chain(&search)
                .map(|base| base.join(&include))
                .find(|candidate| candidate.is_file())
                .with_context(|| format!("{} includes missing \"{include}\"", path.display()))?;
            pending.push(found.canonicalize()?);
        }
        files.push((path, text));
    }
    // A macro like `TS_PUBLIC` is invisible to the compiler but not to a
    // parser that cannot expand it, which then misreads the declaration. Blank
    // its uses, keeping every byte offset, and read the file again.
    for (path, text) in files {
        let tree = parser
            .parse(&text, None)
            .with_context(|| format!("failed to parse {}", path.display()))?;
        let mut blanked = text.clone().into_bytes();
        blank_annotation_uses(
            tree.root_node(),
            text.as_bytes(),
            &annotations,
            &mut blanked,
        );
        let blanked = String::from_utf8(blanked)?;
        let tree = parser
            .parse(&blanked, None)
            .with_context(|| format!("failed to parse {}", path.display()))?;
        collect_definitions(
            tree.root_node(),
            blanked.as_bytes(),
            &mut symbols,
            &mut Vec::new(),
        );
    }
    ensure!(
        symbols.len() > 200,
        "found only {} exported C symbols; symbol discovery is broken",
        symbols.len()
    );
    Ok(symbols)
}

/// Object-like macros that expand to nothing or to an attribute in some
/// branch. Removing their uses from a declaration changes no name in it.
fn collect_annotation_macros(
    node: tree_sitter::Node<'_>,
    source: &[u8],
    out: &mut BTreeSet<String>,
) {
    let mut cursor = node.walk();
    for child in node.named_children(&mut cursor) {
        if child.kind() == "preproc_def" {
            let value = child
                .child_by_field_name("value")
                .and_then(|value| value.utf8_text(source).ok())
                .map_or("", str::trim);
            let is_annotation = value.is_empty()
                || value.starts_with("__attribute__")
                || value.starts_with("__declspec");
            if let Some(name) = child
                .child_by_field_name("name")
                .and_then(|name| name.utf8_text(source).ok())
                .filter(|_| is_annotation)
            {
                out.insert(name.to_string());
            }
        } else {
            collect_annotation_macros(child, source, out);
        }
    }
}

fn blank_annotation_uses(
    node: tree_sitter::Node<'_>,
    source: &[u8],
    annotations: &BTreeSet<String>,
    out: &mut [u8],
) {
    fn walk(
        node: tree_sitter::Node<'_>,
        inside: bool,
        source: &[u8],
        annotations: &BTreeSet<String>,
        out: &mut [u8],
    ) {
        let inside =
            inside || matches!(node.kind(), "declaration" | "function_definition" | "ERROR");
        if inside
            && matches!(node.kind(), "identifier" | "type_identifier")
            && node
                .utf8_text(source)
                .is_ok_and(|text| annotations.contains(text))
        {
            out[node.byte_range()].fill(b' ');
            return;
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            walk(child, inside, source, annotations, out);
        }
    }
    walk(node, false, source, annotations, out);
}

/// The libc a `wasm32-unknown-unknown` build compiles in, behind this macro.
/// Its names must stay the ones C expects.
const WASM32_LIBC_MACRO: &str = "TREE_SITTER_WASM_STDLIB";

/// Collect definitions with external linkage, and the local `#include`s to
/// read next. Every preprocessor branch is read, since a host build takes
/// some and a Wasm-enabled build others, except the `wasm32` libc.
fn collect_definitions(
    node: tree_sitter::Node<'_>,
    source: &[u8],
    out: &mut BTreeSet<String>,
    includes: &mut Vec<String>,
) {
    let mut cursor = node.walk();
    for child in node.named_children(&mut cursor) {
        match child.kind() {
            "preproc_include" => {
                if let Some(path) = child
                    .child_by_field_name("path")
                    .filter(|path| path.kind() == "string_literal")
                    .and_then(|path| path.utf8_text(source).ok())
                {
                    includes.push(path.trim_matches('"').to_string());
                }
            }
            "preproc_ifdef"
                if child
                    .child_by_field_name("name")
                    .and_then(|name| name.utf8_text(source).ok())
                    == Some(WASM32_LIBC_MACRO) =>
            {
                if let Some(alternative) = child.child_by_field_name("alternative") {
                    collect_definitions(alternative, source, out, includes);
                }
            }
            "preproc_if" | "preproc_ifdef" | "preproc_else" | "preproc_elif"
            | "preproc_elifdef" => collect_definitions(child, source, out, includes),
            "function_definition" if !has_storage_class(child, source, &["static"]) => {
                if let Some(name) = child
                    .child_by_field_name("declarator")
                    .and_then(|declarator| declared_name(declarator, source, true))
                {
                    out.insert(name);
                }
            }
            "declaration" if !has_storage_class(child, source, &["static", "extern"]) => {
                let mut declarators = child.walk();
                for declarator in child.children_by_field_name("declarator", &mut declarators) {
                    if let Some(name) = declared_name(declarator, source, false) {
                        out.insert(name);
                    }
                }
            }
            _ => {}
        }
    }
}

fn has_storage_class(node: tree_sitter::Node<'_>, source: &[u8], classes: &[&str]) -> bool {
    let mut cursor = node.walk();
    let found = node.children(&mut cursor).any(|child| {
        child.kind() == "storage_class_specifier"
            && child
                .utf8_text(source)
                .is_ok_and(|text| classes.contains(&text))
    });
    found
}

/// The identifier a declarator introduces. A function declarator names a
/// function; in a plain declaration it is only a prototype, which defines
/// nothing, unless it declares a function pointer, `(*name)(...)`, which is a
/// variable like any other.
fn declared_name(
    declarator: tree_sitter::Node<'_>,
    source: &[u8],
    is_definition: bool,
) -> Option<String> {
    match declarator.kind() {
        "identifier" => declarator.utf8_text(source).ok().map(str::to_string),
        "function_declarator"
            if !is_definition
                && declarator
                    .child_by_field_name("declarator")
                    .is_none_or(|inner| inner.kind() != "parenthesized_declarator") =>
        {
            None
        }
        "function_declarator"
        | "init_declarator"
        | "pointer_declarator"
        | "array_declarator"
        | "parenthesized_declarator"
        | "attributed_declarator" => {
            let inner = declarator.child_by_field_name("declarator").or_else(|| {
                let mut cursor = declarator.walk();
                let found = declarator.named_children(&mut cursor).find(|child| {
                    child.kind().ends_with("declarator") || child.kind() == "identifier"
                });
                found
            })?;
            declared_name(inner, source, is_definition)
        }
        _ => None,
    }
}

/// A digest of the patched C sources, taken before prefixing. Query analysis
/// snapshots carry it, so a library whose analysis code changed rejects
/// snapshots another one wrote instead of trusting them.
fn source_fingerprint(src: &Path) -> Result<String> {
    let mut hasher = <sha2::Sha256 as sha2::Digest>::new();
    for relative in generated_files(src)? {
        let bytes = fs::read(src.join(&relative))?;
        let name = relative.to_string_lossy().replace('\\', "/");
        sha2::Digest::update(&mut hasher, name.as_bytes());
        sha2::Digest::update(&mut hasher, [0]);
        sha2::Digest::update(&mut hasher, (bytes.len() as u64).to_le_bytes());
        sha2::Digest::update(&mut hasher, &bytes);
    }
    let digest = sha2::Digest::finalize(hasher);
    Ok(digest[..8].iter().fold(String::new(), |mut hex, byte| {
        let _ = write!(hex, "{byte:02x}");
        hex
    }))
}

/// Rename every exported C symbol by including a generated header of
/// `#define`s ahead of anything else in the amalgamated `lib.c`, which also
/// defines the source fingerprint the query analysis snapshots carry.
fn prefix_c_symbols(src: &Path, symbols: &BTreeSet<String>, fingerprint: &str) -> Result<()> {
    let mut header = String::from(
        "// Generated by `mise run tree-sitter-sync`. Do not edit.\n\
         // Gives every symbol this library exports a `lumis_` prefix, so it can be\n\
         // linked into the same binary as upstream tree-sitter.\n\
         #ifndef LUMIS_TREE_SITTER_PREFIX_H_\n\
         #define LUMIS_TREE_SITTER_PREFIX_H_\n\n",
    );
    writeln!(
        header,
        "#define LUMIS_QUERY_ANALYSIS_FINGERPRINT 0x{fingerprint}ull\n"
    )?;
    for symbol in symbols {
        writeln!(header, "#define {symbol} {SYMBOL_PREFIX}{symbol}")?;
    }
    header.push_str("\n#endif  // LUMIS_TREE_SITTER_PREFIX_H_\n");
    fs::write(src.join(PREFIX_HEADER), header)?;

    let lib = src.join("lib.c");
    let original = fs::read_to_string(&lib)?;
    fs::write(&lib, format!("#include \"./{PREFIX_HEADER}\"\n{original}"))?;
    Ok(())
}

/// Point each Rust import of an exported symbol at its prefixed name, in every
/// `extern` block of every binding file, however deeply nested. Each file is
/// parsed to find the declarations; only `#[link_name]` lines are inserted, so
/// the rest stays byte-identical to upstream.
fn prefix_rust_imports(dir: &Path, symbols: &BTreeSet<String>) -> Result<()> {
    let mut renamed = 0;
    for entry in glob::glob(&dir.join("*.rs").to_string_lossy())? {
        let path = entry?;
        let text = fs::read_to_string(&path)?;
        let file = syn::parse_file(&text)
            .with_context(|| format!("failed to parse {}", path.display()))?;
        let mut imports = Imports::default();
        syn::visit::Visit::visit_file(&mut imports, &file);
        let mut inserts = Vec::new();
        for (name, start) in imports.found {
            if !symbols.contains(&name) {
                ensure!(
                    !name.starts_with("ts_"),
                    "{} imports `{name}`, which the C library does not export",
                    path.display()
                );
                continue;
            }
            let offset = byte_offset(&text, start.line, start.column)?;
            let line_start = text[..offset].rfind('\n').map_or(0, |index| index + 1);
            let indent = &text[line_start..offset];
            inserts.push((
                offset,
                format!("#[link_name = \"{SYMBOL_PREFIX}{name}\"]\n{indent}"),
            ));
        }
        if inserts.is_empty() {
            continue;
        }
        renamed += inserts.len();
        let mut rewritten = text;
        inserts.sort_by_key(|(offset, _)| std::cmp::Reverse(*offset));
        for (offset, attribute) in inserts {
            rewritten.insert_str(offset, &attribute);
        }
        fs::write(&path, rewritten)?;
    }
    ensure!(
        renamed > 100,
        "renamed only {renamed} Rust imports; discovery is broken"
    );
    Ok(())
}

/// Every function and static an `extern` block declares, with where its
/// declaration starts: the first attribute, or else the visibility or keyword.
#[derive(Default)]
struct Imports {
    found: Vec<(String, proc_macro2::LineColumn)>,
}

impl<'ast> syn::visit::Visit<'ast> for Imports {
    fn visit_foreign_item_fn(&mut self, item: &'ast syn::ForeignItemFn) {
        let start = item.attrs.iter().find(|attr| !is_doc(attr)).map_or_else(
            || declaration_start(&item.vis, syn::spanned::Spanned::span(&item.sig)),
            |attr| syn::spanned::Spanned::span(attr).start(),
        );
        self.found.push((item.sig.ident.to_string(), start));
    }

    fn visit_foreign_item_static(&mut self, item: &'ast syn::ForeignItemStatic) {
        let start = item.attrs.iter().find(|attr| !is_doc(attr)).map_or_else(
            || declaration_start(&item.vis, item.static_token.span),
            |attr| syn::spanned::Spanned::span(attr).start(),
        );
        self.found.push((item.ident.to_string(), start));
    }
}

fn is_doc(attr: &syn::Attribute) -> bool {
    attr.path().is_ident("doc")
}

fn declaration_start(vis: &syn::Visibility, keyword: proc_macro2::Span) -> proc_macro2::LineColumn {
    match vis {
        syn::Visibility::Inherited => keyword.start(),
        vis => syn::spanned::Spanned::span(vis).start(),
    }
}

/// Compile the prefixed library and read its symbol table: whatever the
/// syntax-tree reading above missed would show up here as an unprefixed
/// global, which would collide with upstream tree-sitter's.
fn verify_prefixed(src: &Path) -> Result<()> {
    let host = host_triple()?;
    let objects_dir = src.with_file_name("objects");
    fs::create_dir_all(&objects_dir)?;
    let objects = cc::Build::new()
        .file(src.join("lib.c"))
        .include(src)
        .include(src.with_file_name("include"))
        .define("_POSIX_C_SOURCE", "200112L")
        .define("_DEFAULT_SOURCE", None)
        .define("_BSD_SOURCE", None)
        .define("_DARWIN_C_SOURCE", None)
        .target(&host)
        .host(&host)
        .opt_level(0)
        .cargo_metadata(false)
        .warnings(false)
        .out_dir(&objects_dir)
        .try_compile_intermediates()
        .context("failed to compile the prefixed tree-sitter library")?;
    let mut unprefixed = Vec::new();
    let mut checked = 0;
    for path in objects {
        let bytes = fs::read(&path)?;
        let file = object::File::parse(bytes.as_slice())?;
        let mangling = if matches!(file.format(), object::BinaryFormat::MachO) {
            "_"
        } else {
            ""
        };
        for symbol in object::Object::symbols(&file) {
            use object::ObjectSymbol as _;
            if !symbol.is_global() || symbol.is_undefined() {
                continue;
            }
            let name = symbol.name()?;
            let name = name.strip_prefix(mangling).unwrap_or(name);
            checked += 1;
            if !name.starts_with(SYMBOL_PREFIX) {
                unprefixed.push(name.to_string());
            }
        }
    }
    fs::remove_dir_all(&objects_dir)?;
    ensure!(
        checked > 200,
        "the compiled library defines only {checked} global symbols"
    );
    ensure!(
        unprefixed.is_empty(),
        "the compiled library still exports unprefixed symbols: {}",
        unprefixed.join(", ")
    );
    Ok(())
}

fn host_triple() -> Result<String> {
    let output = Command::new("rustc")
        .arg("-vV")
        .output()
        .context("failed to run rustc -vV")?;
    String::from_utf8(output.stdout)?
        .lines()
        .find_map(|line| line.strip_prefix("host: "))
        .map(str::to_string)
        .context("rustc -vV printed no host triple")
}

/// proc-macro2 reports 1-based lines and 0-based columns in characters.
fn byte_offset(text: &str, line: usize, column: usize) -> Result<usize> {
    let line_start: usize = text
        .split_inclusive('\n')
        .take(line - 1)
        .map(str::len)
        .sum();
    let rest = &text[line_start..];
    let within = rest
        .char_indices()
        .nth(column)
        .map_or(rest.len(), |(index, _)| index);
    ensure!(line_start + within <= text.len(), "span out of range");
    Ok(line_start + within)
}

/// The version release tooling last set, which a regeneration must keep.
fn committed_version(crate_dir: &Path) -> Result<String> {
    let Ok(text) = fs::read_to_string(crate_dir.join("Cargo.toml")) else {
        return Ok(INITIAL_VERSION.to_string());
    };
    let manifest: toml_edit::DocumentMut = text.parse()?;
    manifest["package"]["version"]
        .as_str()
        .map(str::to_string)
        .context("crates/lumis-tree-sitter/Cargo.toml has no package.version")
}

fn rewrite_manifest(path: &Path, version: &str) -> Result<()> {
    let mut manifest: toml_edit::DocumentMut = fs::read_to_string(path)?.parse()?;
    let package = &mut manifest["package"];
    package["name"] = toml_edit::value("lumis-tree-sitter");
    package["version"] = toml_edit::value(version);
    package["links"] = toml_edit::value("lumis-tree-sitter");
    package["description"] = toml_edit::value(
        "Tree-sitter's parsing library with the patches Lumis needs, linkable beside upstream tree-sitter",
    );
    package["readme"] = toml_edit::value("README.md");
    package["repository"] = toml_edit::value("https://github.com/leandrocp/lumis");
    package["homepage"] = toml_edit::value("https://lumis.sh");
    package["documentation"] = toml_edit::value("https://docs.rs/lumis-tree-sitter");
    let include = package["include"]
        .as_array_mut()
        .context("the upstream manifest has no `include` list")?;
    include.push("/README.md");
    manifest["lib"]["name"] = toml_edit::value("lumis_tree_sitter");

    // Bindings generated at build time would import the unprefixed names, and
    // link against upstream's library wherever both are in one binary.
    let build_dependencies = manifest["build-dependencies"]
        .as_table_like_mut()
        .context("the upstream manifest has no build-dependencies")?;
    ensure!(
        build_dependencies.remove("bindgen").is_some(),
        "the upstream manifest no longer has the optional `bindgen` build dependency"
    );
    // Upstream's code is held to upstream's lints, tests and formatting, not
    // this workspace's; it is a member only so it packages with its dependents.
    let lints: toml_edit::DocumentMut = r#"
[lints.rust]
mismatched_lifetime_syntaxes = "allow"
unexpected_cfgs = { level = "warn", check-cfg = ['cfg(feature, values("bindgen"))'] }

[lints.clippy]
all = { level = "allow", priority = -1 }
pedantic = { level = "allow", priority = -1 }
nursery = { level = "allow", priority = -1 }
cargo = { level = "allow", priority = -1 }
"#
    .parse()?;
    manifest["lints"] = lints["lints"].clone();
    manifest["lib"]["test"] = toml_edit::value(false);
    manifest["lib"]["doctest"] = toml_edit::value(false);

    let text = format!(
        "# Generated by `mise run tree-sitter-sync` from the tree-sitter crate pinned in\n\
         # upstream.toml. Do not edit; see README.md.\n{manifest}"
    );
    fs::write(path, text)?;
    Ok(())
}

fn readme(upstream: &Upstream, patches: &[Patch], symbol_count: usize) -> String {
    let mut out = format!(
        "<!-- Generated by `mise run tree-sitter-sync`. Do not edit. -->\n\
         # lumis-tree-sitter\n\n\
         The [tree-sitter](https://crates.io/crates/tree-sitter) {version} crate with the patches\n\
         below applied, published so Lumis can ship them. Every file except\n\
         `upstream.toml`, `patches/` and `CHANGELOG.md` is generated from that release and\n\
         those patches; nothing here is edited by hand.\n\n\
         Use it through a renamed dependency so code keeps saying `tree_sitter`:\n\n\
         ```toml\n\
         tree-sitter = {{ package = \"lumis-tree-sitter\", version = \"…\" }}\n\
         ```\n\n\
         ## What differs from tree-sitter {version}\n\n",
        version = upstream.version
    );
    for patch in patches {
        let _ = write!(
            out,
            "### {}\n\n`patches/{}`\n\n{}\n\n",
            patch.subject, patch.file_name, patch.description
        );
    }
    let _ = write!(
        out,
        "### Every exported C symbol is prefixed with `{SYMBOL_PREFIX}`\n\n\
         Applied last, so it covers what the patches add. `src/{PREFIX_HEADER}` renames\n\
         {symbol_count} names: every function and variable the library defines with external\n\
         linkage, plus a few static ones a macro hides from the source reader, which renaming\n\
         does not affect. The Rust bindings import them under the new names. The crate's `links` key is\n\
         `lumis-tree-sitter`, so it builds and links beside upstream `tree-sitter` instead of\n\
         being rejected by Cargo, and neither one calls the other's C code.\n\n\
         Wasmtime is the exception: its C API crate declares `links = \"wasmtime-c-api\"`, so\n\
         a project that also enables upstream's `wasm` feature resolves only when both pin\n\
         the same Wasmtime major. The pin follows the newest tree-sitter release to keep\n\
         that true.\n\n\
         The optional `bindgen` build dependency is removed, because bindings generated at\n\
         build time would import the unprefixed names.\n\n\
         Parsers are unaffected: a Wasm parser's imports and exports are matched by name\n\
         strings, not by these symbols, so the same parser loads in both libraries.\n"
    );
    out
}

fn generated_files(root: &Path) -> Result<BTreeSet<PathBuf>> {
    let mut files = BTreeSet::new();
    for entry in glob::glob(&root.join("**/*").to_string_lossy())? {
        let path = entry?;
        if !path.is_file() {
            continue;
        }
        let relative = path.strip_prefix(root)?.to_path_buf();
        let top = relative
            .components()
            .next()
            .map(|component| component.as_os_str().to_string_lossy().into_owned());
        if top.is_some_and(|top| AUTHORED.contains(&top.as_str())) {
            continue;
        }
        files.insert(relative);
    }
    Ok(files)
}

fn compare(crate_dir: &Path, staging: &Path) -> Result<()> {
    let expected = generated_files(staging)?;
    let actual = generated_files(crate_dir)?;
    let mut stale = Vec::new();
    for path in expected.union(&actual) {
        let ours = fs::read(crate_dir.join(path)).ok();
        let theirs = fs::read(staging.join(path)).ok();
        if ours != theirs {
            stale.push(path.display().to_string());
        }
    }
    if !stale.is_empty() {
        bail!(
            "crates/lumis-tree-sitter is not what upstream.toml and patches/ generate. \
             Run `mise run tree-sitter-sync` instead of editing it by hand:\n  {}",
            stale.join("\n  ")
        );
    }
    println!("crates/lumis-tree-sitter matches upstream.toml and patches/");
    Ok(())
}

fn replace(crate_dir: &Path, staging: &Path) -> Result<()> {
    for path in generated_files(crate_dir)? {
        fs::remove_file(crate_dir.join(path))?;
    }
    for path in generated_files(staging)? {
        let target = crate_dir.join(&path);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::copy(staging.join(&path), target)?;
    }
    remove_empty_dirs(crate_dir)?;
    println!("regenerated crates/lumis-tree-sitter");
    Ok(())
}

fn remove_empty_dirs(dir: &Path) -> Result<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            remove_empty_dirs(&path)?;
            if fs::read_dir(&path)?.next().is_none() {
                fs::remove_dir(&path)?;
            }
        }
    }
    Ok(())
}
